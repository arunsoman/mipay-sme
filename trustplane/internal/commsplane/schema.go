package commsplane

// DDL for the comms database (comms-design.md §5, the B0 subset). Idempotent, applied at boot.
var DDL = []string{
	`CREATE TABLE IF NOT EXISTS tenants(
		id TEXT PRIMARY KEY,
		name TEXT NOT NULL,
		default_locale TEXT NOT NULL DEFAULT 'en',
		sandbox BOOLEAN NOT NULL DEFAULT FALSE,
		created_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
	`INSERT INTO tenants (id, name) VALUES ('platform', 'MiPay platform') ON CONFLICT (id) DO NOTHING`,
	`CREATE TABLE IF NOT EXISTS requests(
		id TEXT PRIMARY KEY,
		tenant_id TEXT NOT NULL REFERENCES tenants(id),
		client_id TEXT NOT NULL,
		idempotency_key TEXT,
		event_code TEXT NOT NULL,
		lane TEXT NOT NULL,
		recipients INTEGER NOT NULL,
		created_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
	`CREATE UNIQUE INDEX IF NOT EXISTS requests_idem_uq ON requests (tenant_id, client_id, idempotency_key) WHERE idempotency_key IS NOT NULL`,
	// The body and variable VALUES are never stored here (H8): only the names.
	`CREATE TABLE IF NOT EXISTS messages(
		id TEXT PRIMARY KEY,
		request_id TEXT NOT NULL REFERENCES requests(id),
		tenant_id TEXT NOT NULL,
		client_id TEXT NOT NULL,
		event_code TEXT NOT NULL,
		recipient_ref TEXT NOT NULL,
		lane TEXT NOT NULL,
		category TEXT NOT NULL,
		sensitivity TEXT NOT NULL DEFAULT 'NORMAL',
		channel TEXT,
		address_masked TEXT,
		template_version_id BIGINT,
		locale TEXT NOT NULL DEFAULT 'en',
		data_names TEXT[] NOT NULL DEFAULT '{}',
		status TEXT NOT NULL,
		status_reason TEXT,
		provider_id TEXT,
		provider_msg_id TEXT,
		expires_at TIMESTAMPTZ,
		created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
		updated_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
	`ALTER TABLE messages ADD COLUMN IF NOT EXISTS seq INTEGER NOT NULL DEFAULT 0`, // position in the request's to[]
	`CREATE INDEX IF NOT EXISTS messages_request_idx ON messages (request_id)`,
	`CREATE INDEX IF NOT EXISTS messages_recipient_idx ON messages (recipient_ref, created_at)`,
	`CREATE TABLE IF NOT EXISTS message_events(
		id BIGSERIAL PRIMARY KEY,
		message_id TEXT NOT NULL REFERENCES messages(id),
		at TIMESTAMPTZ NOT NULL DEFAULT now(),
		status TEXT NOT NULL,
		detail JSONB NOT NULL DEFAULT '{}'::jsonb)`,
	`CREATE INDEX IF NOT EXISTS message_events_msg_idx ON message_events (message_id, id)`,
	`CREATE TABLE IF NOT EXISTS attempts(
		message_id TEXT NOT NULL REFERENCES messages(id),
		n INTEGER NOT NULL,
		provider_id TEXT NOT NULL,
		provider_msg_id TEXT,
		started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
		finished_at TIMESTAMPTZ,
		result TEXT,
		error_class TEXT,
		PRIMARY KEY (message_id, n))`,
	`CREATE INDEX IF NOT EXISTS attempts_provider_msg_idx ON attempts (provider_msg_id)`,
	// Transactional outbox: written with the message; the relay moves rows into the queue.
	`CREATE TABLE IF NOT EXISTS outbox(
		id BIGSERIAL PRIMARY KEY,
		message_id TEXT NOT NULL REFERENCES messages(id),
		lane TEXT NOT NULL,
		tenant_id TEXT NOT NULL,
		payload BYTEA NOT NULL,
		created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
		published_at TIMESTAMPTZ)`,
	`CREATE INDEX IF NOT EXISTS outbox_unpublished_idx ON outbox (id) WHERE published_at IS NULL`,
	// Phase-1 queue (FOR UPDATE SKIP LOCKED). payload is AES-GCM sealed and wiped on a terminal state.
	`CREATE TABLE IF NOT EXISTS jobs(
		id BIGSERIAL PRIMARY KEY,
		stage TEXT NOT NULL CHECK (stage IN ('plan','dispatch')),
		lane TEXT NOT NULL,
		tenant_bucket TEXT NOT NULL,
		message_id TEXT NOT NULL REFERENCES messages(id),
		available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
		lease_until TIMESTAMPTZ,
		attempts INTEGER NOT NULL DEFAULT 0,
		dead BOOLEAN NOT NULL DEFAULT FALSE,
		dead_reason TEXT,
		payload BYTEA NOT NULL,
		created_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
	`CREATE INDEX IF NOT EXISTS jobs_lease_idx ON jobs (stage, lane, available_at) WHERE NOT dead`,
	`CREATE TABLE IF NOT EXISTS template_versions(
		id BIGSERIAL PRIMARY KEY,
		tenant_id TEXT,
		event_code TEXT NOT NULL,
		channel TEXT NOT NULL,
		locale TEXT NOT NULL,
		version INTEGER NOT NULL,
		status TEXT NOT NULL CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED')),
		subject TEXT NOT NULL DEFAULT '',
		body TEXT NOT NULL,
		variables TEXT[] NOT NULL DEFAULT '{}',
		content_hash TEXT NOT NULL,
		created_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
	`CREATE UNIQUE INDEX IF NOT EXISTS template_versions_uq ON template_versions (COALESCE(tenant_id,''), event_code, channel, locale, version)`,
	// Contacts: address encrypted, blind-index hash for lookups. Written only by the core.
	`CREATE TABLE IF NOT EXISTS contacts(
		tenant_id TEXT NOT NULL DEFAULT 'platform',
		subject_ref TEXT NOT NULL,
		channel TEXT NOT NULL,
		address_enc BYTEA NOT NULL,
		address_hash TEXT NOT NULL,
		address_masked TEXT NOT NULL,
		verified_at TIMESTAMPTZ,
		is_primary BOOLEAN NOT NULL DEFAULT FALSE,
		updated_by TEXT NOT NULL,
		updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
		PRIMARY KEY (tenant_id, subject_ref, channel, address_hash))`,
	`CREATE INDEX IF NOT EXISTS contacts_hash_idx ON contacts (address_hash)`,
	// Sandbox provider output: the only place a rendered secret (OTP, link) is visible (§9).
	`CREATE TABLE IF NOT EXISTS sim_outbox(
		id TEXT PRIMARY KEY,
		message_id TEXT NOT NULL,
		event_code TEXT NOT NULL,
		recipient_ref TEXT NOT NULL,
		channel TEXT NOT NULL,
		address TEXT NOT NULL,
		subject TEXT NOT NULL DEFAULT '',
		body TEXT NOT NULL,
		created_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
	`CREATE INDEX IF NOT EXISTS sim_outbox_recipient_idx ON sim_outbox (recipient_ref, created_at DESC)`,
}
