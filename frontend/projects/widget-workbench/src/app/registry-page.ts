import { ChangeDetectionStrategy, Component, computed, inject, signal } from '@angular/core';
import { HttpClient, HttpErrorResponse } from '@angular/common/http';
import { RouterLink } from '@angular/router';
import { firstValueFrom } from 'rxjs';
import { WIDGETS } from '../../../shared/widgets/registry.generated';
import { TIERS, cellsOf, requiredList } from '../../../shared/widgets/core';
import type { BusinessPortal } from '../../../shared/web-core/portal-permission-catalogue';

interface ServerWidget { id: string; version: string; label: string; category: string; bundle: string; registeredAt: string; contexts: string[] }

/**
 * What the portal builder can discover: the widgets this build registers (generated from the
 * manifests) and - through the dev proxy and a signed-in session - what the registry server
 * holds for a portal (GET /api/ui/widgets?portal=…).
 */
@Component({
  selector: 'wb-registry-page',
  changeDetection: ChangeDetectionStrategy.OnPush,
  imports: [RouterLink],
  template: `
    <h1>Widget registry</h1>
    <p class="dim">This build: {{ widgets.length }} widget(s), generated by <span class="mono">npm run widgets:gen</span>.
      Readiness per widget: <span class="mono">npm run widgets:check</span>.</p>
    <table>
      <thead><tr><th>Widget</th><th>Category</th><th>Portals</th><th>Shows with</th><th>Actions</th><th>Reads / writes</th><th>Span xs · sm · md · lg</th></tr></thead>
      <tbody>
        @for (w of widgets; track w.def.id) {
          <tr>
            <td><a [routerLink]="['/w', w.def.id]">{{ w.def.label }}</a><div class="mono dim small">{{ w.def.id }}&#64;{{ w.def.version }}</div></td>
            <td>{{ w.def.category }}</td>
            <td class="small">{{ w.def.contexts.join(', ') }}</td>
            <td class="mono small">{{ requiresText(w.def) }}</td>
            <td class="small">@for (a of w.def.actions; track a.id) {<div>{{ a.label }} <span class="mono dim">{{ a.cell }}</span></div>}</td>
            <td class="mono small">{{ w.def.sources.length }} sources · {{ w.def.commands.length }} commands</td>
            <td class="mono small">{{ spans(w.def) }}</td>
          </tr>
        }
      </tbody>
    </table>

    <h2>Registry server</h2>
    <p class="dim">What the server holds for a portal (registered at deploy by <span class="mono">npm run widgets:register</span>).
      Needs the dev proxy and a signed-in session that holds <span class="mono">admin.access:read</span>.</p>
    <div class="controls">
      <label>Portal
        <select [value]="portal()" (change)="portal.set($any($event.target).value)">
          @for (p of portals; track p) {<option [value]="p" [selected]="p === portal()">{{ p }}</option>}
        </select>
      </label>
      <button type="button" (click)="fetch()" [disabled]="busy()">{{ busy() ? 'Asking…' : 'Ask the registry server' }}</button>
    </div>
    @if (error(); as e) {<p class="bad">{{ e }}</p>}
    @if (server(); as list) {
      <table>
        <thead><tr><th>Widget</th><th>Version</th><th>Bundle</th><th>Registered</th><th>In this build?</th></tr></thead>
        <tbody>
          @for (s of list; track s.id) {
            <tr><td>{{ s.label }} <span class="mono dim small">{{ s.id }}</span></td><td class="mono">{{ s.version }}</td>
              <td class="mono small">{{ s.bundle }}</td><td class="small">{{ s.registeredAt }}</td>
              <td>{{ local(s.id) }}</td></tr>
          } @empty {<tr><td colspan="5" class="dim">Nothing registered for {{ portal() }}.</td></tr>}
        </tbody>
      </table>
    }
  `,
})
export class RegistryPage {
  private readonly http = inject(HttpClient);
  readonly widgets = WIDGETS;
  readonly portals: BusinessPortal[] = ['PLATFORM', 'MANUFACTURER', 'DISTRIBUTOR', 'SUPPLIER', 'MERCHANT', 'LENDER'];
  readonly portal = signal<BusinessPortal>('SUPPLIER');
  readonly busy = signal(false);
  readonly error = signal('');
  readonly server = signal<ServerWidget[] | null>(null);
  private readonly ids = computed(() => new Map(this.widgets.map((w) => [w.def.id, w.def.version])));

  requiresText(def: (typeof WIDGETS)[number]['def']) {
    const r = requiredList(def);
    return (Array.isArray(def.requires) ? 'any of ' : 'all of ') + r.join(', ') + ` (${cellsOf(def).length} cells)`;
  }
  spans(def: (typeof WIDGETS)[number]['def']) {
    return TIERS.map((t) => { const s = def.size[t]; return s.kind === 'hidden' ? '–' : `${s.min}-${s.default}-${s.max}`; }).join(' · ');
  }
  local(id: string) { const v = this.ids().get(id); return v ? `yes (${v})` : 'no'; }

  async fetch() {
    this.busy.set(true);
    this.error.set('');
    this.server.set(null);
    try {
      this.server.set(await firstValueFrom(this.http.get<ServerWidget[]>('/api/ui/widgets', { params: { portal: this.portal() } })));
    } catch (e) {
      const s = e instanceof HttpErrorResponse ? e.status : 0;
      this.error.set(s === 401 ? 'Not signed in: open /auth/login through the proxy first.'
        : s === 403 ? 'Signed in, but without admin.access:read.'
          : s === 0 || s === 504 || s === 502 ? 'The registry server is not reachable through the dev proxy (proxy.conf.json).'
            : `The registry server answered ${s}.`);
    } finally {
      this.busy.set(false);
    }
  }
}
